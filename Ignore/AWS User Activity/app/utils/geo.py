_SERVICE_UA_RE = re.compile(
    r"^(aws-sdk-|aws-cli|Boto3|Botocore|AWS Internal|cloudformation\.amazonaws\.com)",
    re.IGNORECASE,
)


def is_aws_ip(ip: str) -> bool:
    try:
        addr = ipaddress.ip_address(ip)
    except (ValueError, TypeError):
        return False
    return any(addr in net for net in _AWS_OWNED_PREFIXES)


def is_service_user_agent(ua: str | None) -> bool:
    if not ua:
        return False
    return bool(_SERVICE_UA_RE.search(ua))
